// One-off generator: for each catalog exercise find an embeddable YouTube how-to video and write content-data/videos.ts.
// Usage: bun scripts/find-videos.ts   (needs network; re-runnable, keeps existing entries unless --force)
import { SEED_EXERCISES } from '../src/shared/exercises';
const OUT = new URL('../src/shared/content-data/videos.ts', import.meta.url).pathname;
let existing: Record<string, { v: string; t: string; c: string }> = {};
try { existing = (await import(OUT)).VIDEOS; } catch {}
const force = process.argv.includes('--force');
async function curl(url: string): Promise<{ ok: boolean; body: string }> {
  const p = Bun.spawn(['curl', '-s', '-m', '20', '-A', 'Mozilla/5.0', '-H', 'Accept-Language: en', '-w', '\n%{http_code}', url], { stdout: 'pipe' });
  const t = await new Response(p.stdout).text();
  const i = t.lastIndexOf('\n');
  return { ok: t.slice(i + 1) === '200', body: t.slice(0, i) };
}
async function search(q: string): Promise<string[]> {
  const r = await curl(`https://www.youtube.com/results?search_query=${encodeURIComponent(q)}&sp=EgIQAQ%253D%253D`);
  return [...new Set([...r.body.matchAll(/"videoRenderer":\{"videoId":"([\w-]{11})"/g)].map((m) => m[1]!))].slice(0, 6);
}
async function check(v: string) {
  const r = await curl(`https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${v}&format=json`);
  if (!r.ok) return null;
  const j: any = JSON.parse(r.body);
  return { v, t: String(j.title ?? '').slice(0, 110), c: String(j.author_name ?? '').slice(0, 60) };
}
const out = { ...existing };
const todo = SEED_EXERCISES.filter((e) => force || !out[e.id]);
let i = 0;
await Promise.all(Array.from({ length: 3 }, async () => {
  while (i < todo.length) {
    const e = todo[i++]!;
    try {
      for (const v of await search(`${e.name} proper form how to`)) { const ok = await check(v); if (ok) { out[e.id] = ok; break; } }
    } catch (err) { console.error(e.id, String(err)); }
    if (!out[e.id]) console.error('NONE', e.id);
  }
}));
const body = Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n');
await Bun.write(OUT, `// Generated by scripts/find-videos.ts. v = YouTube id (embeddable-checked via oEmbed), t = title, c = channel. Review before shipping.\nexport const VIDEOS: Record<string, { v: string; t: string; c: string }> = {\n${body}\n};\n`);
console.log(Object.keys(out).length, '/', SEED_EXERCISES.length);
